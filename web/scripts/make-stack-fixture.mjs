// Writes the FIXTURE stack results the revenue-stack UI is built against while Step 1 (the real engine) is unmerged.
// Every number is made up from a fixed formula. Nothing here is a result. The output follows the Stack results schema
// in docs/PLAN_V4.md (results/v4/stack/<year>_<dur>h_<mode>.json) exactly; the only marker is the word FIXTURE in
// meta.generated, meta.sources and meta.assumptions.
//   node scripts/make-stack-fixture.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'fixtures', 'v4', 'stack');
mkdirSync(out, { recursive: true });

const PRODUCTS = ['energy', 'regup', 'regdn', 'rrs', 'ecrs', 'nsrs'];
// 3 hubs and 3 nodes, with made-up 2 h perfect-foresight $/kW-yr by product.
const BASE = {
  HB_HOUSTON: [40, 5, 3, 9, 5, 1],
  HB_NORTH: [44, 6, 3, 10, 5, 1],
  HB_WEST: [49, 7, 4, 11, 6, 1],
  RUSSEKST_RN: [176, 9, 5, 12, 7, 2],
  ANSON1_ALL: [47, 6, 3, 9, 5, 1],
  CAMWIND_RN: [43, 5, 3, 8, 4, 1],
};
const YEARS = { 2025: { energy: 1, as: 1, rtcb: 'mixed', partial: false, months: 12 }, 2026: { energy: 0.85, as: 0.7, rtcb: 'post', partial: true, months: 10 } };
const DURS = { 2: { energy: 1, as: 1 }, 4: { energy: 1.6, as: 1.05 } };
const MODES = { foresight: { energy: 1, as: 1 }, realistic: { energy: 0.6, as: 0.8 } };
const r2 = (x) => Math.round(x * 100) / 100;

for (const [year, y] of Object.entries(YEARS)) {
  for (const [dur, d] of Object.entries(DURS)) {
    for (const [mode, m] of Object.entries(MODES)) {
      const nodes = {};
      for (const [code, b] of Object.entries(BASE)) {
        const v = b.map((x, i) => r2(x * (i === 0 ? y.energy * d.energy * m.energy : y.as * d.as * m.as)));
        const [energy, regup, regdn, rrs, ecrs, nsrs] = v;
        nodes[code] = { energy, regup, regdn, rrs, ecrs, nsrs, total: r2(v.reduce((s, x) => s + x, 0)) };
      }
      const file = {
        meta: {
          year: Number(year), durationH: Number(dur), mode, products: PRODUCTS, partialYear: y.partial, monthsCovered: y.months, rtcb: y.rtcb,
          assumptions: ['FIXTURE: every number is made up to exercise the UI. It is not a result and not a forecast.'],
          sources: ['FIXTURE: none. Generated by web/scripts/make-stack-fixture.mjs.'],
          generated: 'FIXTURE (not generated by the Step 1 engine)',
        },
        nodes,
      };
      writeFileSync(join(out, `${year}_${dur}h_${mode}.json`), JSON.stringify(file, null, 1) + '\n');
    }
  }
}
console.log('wrote 8 FIXTURE files to', out);

// index.json lists the files, as the Step 1 engine's index does for the real results (the Site Value card reads it).
import { readdirSync } from 'node:fs';
const files = readdirSync(out).filter((f) => /^\d{4}_\d+h_(foresight|realistic)\.json$/.test(f)).sort();
writeFileSync(join(out, 'index.json'), JSON.stringify({ files }, null, 1) + '\n');
