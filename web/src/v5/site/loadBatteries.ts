import dataVersion from '../../data/data-version.json'; // generated by scripts/copy-data.mjs
import { parseBatteries } from './report';
import type { BatteriesFile } from '../nearby';

let cached: Promise<BatteriesFile | null> | null = null;

/** results/v5/batteries/tx_batteries.json. A missing, unreadable or odd file gives null, and the report hides its Storage nearby section. */
export function loadBatteries(): Promise<BatteriesFile | null> {
  cached ??= fetch(`${import.meta.env.BASE_URL}data/v5/batteries/tx_batteries.json?v=${dataVersion.version}`)
    .then((r) => (r.ok ? r.json() : null))
    .then(parseBatteries)
    .catch(() => null);
  return cached;
}
