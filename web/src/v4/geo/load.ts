import dataVersion from '../../data/data-version.json'; // generated by scripts/copy-data.mjs
import type { CountyInput } from './search';
import type { NodeIndex, Place } from './types';

// Loaded only when a V4 screen asks for them. Nothing here runs at start-up.
const BASE = `${import.meta.env.BASE_URL}data/v4/geo/`;
const cache = new Map<string, Promise<unknown>>();

function getJson<T>(file: string): Promise<T> {
  let p = cache.get(file);
  if (!p) {
    p = fetch(`${BASE}${file}?v=${dataVersion.version}`).then((r) => {
      if (!r.ok) throw new Error(`${file}: HTTP ${r.status}`);
      return r.json();
    });
    p.catch(() => cache.delete(file));
    cache.set(file, p);
  }
  return p as Promise<T>;
}

/** Outlines for the map (TopoJSON, county name and FIPS on each shape). Decoded by the map layer in Step 4. */
export const loadCountiesTopo = () => getJson<unknown>('tx_counties.topo.json');
export const loadCountyIndex = () => getJson<(CountyInput & { fips: string })[]>('county_index.json');
export const loadPlaces = () => getJson<Place[]>('places.json');
export const loadNodeIndex = () => getJson<NodeIndex>('node_index.json');
