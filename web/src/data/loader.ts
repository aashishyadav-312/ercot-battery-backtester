import type { IndexRun, LocationsFile, NodeSelection, NodesFile, TexasGeo, Rtcb, Run, Selection, Walkthrough } from './types';
import dataVersion from './data-version.json'; // generated by scripts/copy-data.mjs

const BASE = `${import.meta.env.BASE_URL}data/`;
/** Changes whenever results/*.json change, so browsers never mix cached old data with a new build. */
const DATA_VERSION = dataVersion.version;
const cache = new Map<string, Promise<unknown>>();

function getJson<T>(file: string): Promise<T> {
  let p = cache.get(file);
  if (!p) {
    p = fetch(`${BASE}${file}?v=${DATA_VERSION}`).then((r) => {
      if (!r.ok) throw new Error(`${file}: HTTP ${r.status}`);
      return r.json();
    });
    p.catch(() => cache.delete(file)); // allow retry after a failure
    cache.set(file, p);
  }
  return p as Promise<T>;
}

export const loadIndex = () => getJson<{ runs: IndexRun[] }>('index.json').then((d) => d.runs);
export const loadNodeSelection = () => getJson<NodeSelection>('node_selection.json');
export const loadRtcb = () => getJson<Rtcb>('rtcb.json');
export const loadWalkthrough = () => getJson<Walkthrough>('walkthrough.json');
export const loadLocations = () => getJson<LocationsFile>('locations.json');
export const loadTexas = () => getJson<TexasGeo>('texas.json');
/** All resource nodes for the standard configuration (Phase 12). Only the Map page asks for it, so other pages never download it. */
export const ALL_NODES_FILE = 'nodes_2025_2h.json';
export const loadNodes = () => getJson<NodesFile>(ALL_NODES_FILE);
export const loadRun = (file: string) => getJson<Run>(file);

export function findRun(index: IndexRun[], s: Selection, location = s.location, year = s.year, duration = s.duration) {
  return index.find(
    (r) => r.location === location && r.year === year && r.duration_h === duration && r.deg_cost_per_mwh === s.deg,
  );
}

