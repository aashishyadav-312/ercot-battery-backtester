const BASE = `${import.meta.env.BASE_URL}data/`;
/** Changes whenever results/*.json change, so browsers never mix cached old data with a new build. */
const DATA_VERSION = dataVersion.version;
const cache = new Map<string, Promise<unknown>>();

function getJson<T>(file: string): Promise<T> {
  let p = cache.get(file);
  if (!p) {
    p = fetch(`${BASE}${file}?v=${DATA_VERSION}`).then((r) => {
      if (!r.ok) throw new Error(`${file}: HTTP ${r.status}`);
      return r.json();
    });
    p.catch(() => cache.delete(file)); // allow retry after a failure
    cache.set(file, p);
  }
  return p as Promise<T>;
}

function getText(file: string): Promise<string> {
  const key = `text:${file}`;
  let p = cache.get(key);
  if (!p) {
    p = fetch(`${BASE}${file}?v=${DATA_VERSION}`).then((r) => {
      if (!r.ok) throw new Error(`${file}: HTTP ${r.status}`);
      return r.text();
    });
    p.catch(() => cache.delete(key));
    cache.set(key, p);
  }
  return p as Promise<string>;
}

