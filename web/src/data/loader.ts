export const loadStack = (year: number, durationH: number, mode: StackMode) =>
  getJson<StackFile>(stackPath(year, durationH, mode)).then((f) => {
    // Made-up FIXTURE files exist only for unit tests. A production build never serves them (copy-data.mjs, check-no-fixture.mjs);
    // this is the last line: refuse one if it ever arrives, so it reads as "no file", never as a result.
    if (import.meta.env.PROD && isFixture(f)) throw new Error('FIXTURE stack data is not allowed in production');
    return f;
  });
